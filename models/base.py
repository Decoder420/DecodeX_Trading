"""Base interface and standard signal packet definition for all signal models."""

from __future__ import annotations

from abc import ABC, abstractmethod
from dataclasses import dataclass, field
from enum import Enum
from typing import Any, Dict, List, Optional
import pandas as pd


class SignalDirection(str, Enum):
    BUY = "BUY"
    SELL = "SELL"
    NO_TRADE = "NO_TRADE"

    @classmethod
    def from_numeric(cls, val: int | float) -> SignalDirection:
        if val > 0:
            return cls.BUY
        elif val < 0:
            return cls.SELL
        return cls.NO_TRADE

    def to_numeric(self) -> int:
        if self == SignalDirection.BUY:
            return 1
        elif self == SignalDirection.SELL:
            return -1
        return 0


@dataclass
class SignalPacket:
    """Standard output packet generated by any signal model for every bar t."""
    direction: SignalDirection
    confidence: float                 # Calibrated probability of the predicted direction in [0.0, 1.0]
    suggested_entry: float            # Close price of bar t (reference execution entry is Open of t+1)
    stop_loss: float                  # ATR-based risk boundary
    take_profit: float                # ATR-based reward target
    reasons: str                      # Decision rationale (Rule trace or SHAP top feature drivers)
    margin: float = 0.0               # Difference between winning probability and runner-up class
    class_probs: Dict[int, float] = field(default_factory=dict) # Full class distribution {-1, 0, 1}


class BaseSignalModel(ABC):
    """Abstract base class for all quantitative signal generation models."""

    def __init__(self, name: str, params: Optional[Dict[str, Any]] = None) -> None:
        self.name = name
        self.params = params or {}
        self.is_fitted = False

    @abstractmethod
    def fit(self, train_df: pd.DataFrame, **kwargs: Any) -> BaseSignalModel:
        """Fit model parameters strictly on training fold data."""
        pass

    @abstractmethod
    def predict_signals(self, df: pd.DataFrame, **kwargs: Any) -> pd.DataFrame:
        """Generate DataFrame of SignalPacket columns for every candle in df.

        Returns DataFrame with columns:
        ['direction', 'confidence', 'suggested_entry', 'stop_loss', 'take_profit', 'reasons', 'margin']
        """
        pass
